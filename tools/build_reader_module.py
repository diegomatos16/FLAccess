"""Assemble ordered Reader sources into one Sider-compatible Lua chunk.

Fragments share lexical scope. No runtime imports or additional DLLs.
"""
from pathlib import Path
import argparse

FRAGMENTS = ('bootstrap', 'memory_prism', 'text_intents', 'speech_queue', 'semantics', 'review', 'native_tree', 'native_windows', 'presentation', 'players', 'controls', 'observations', 'resolver', 'focus', 'frame', 'lifecycle')
HEADER = '-- Generated by tools/build_reader_module.py; edit engine sources.\n'


def render(root):
    engine = Path(root) / 'modules/FlAccessReader/engine'
    # Read everything before writing: missing fragments cannot truncate runtime.
    return HEADER + ''.join((engine / (name + '.lua')).read_text(encoding='utf-8')
                            for name in FRAGMENTS)


def build(root, check=False):
    target = Path(root) / 'modules/FlAccessReader/FlAccessReader.lua'
    expected = render(root).encode('utf-8')
    if check:
        if target.read_bytes() != expected:
            raise ValueError('Reader bundle is stale; run tools/build_reader_module.py')
    else:
        target.write_bytes(expected)
    return target


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--root', type=Path, default=Path(__file__).resolve().parents[1])
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    print('READER_BUNDLE_OK', build(args.root, check=args.check))
