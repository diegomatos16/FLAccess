"""Bundle independent Gameplay engines for Sider's restricted Lua environment."""
from pathlib import Path
import argparse

def build(root):
    root = Path(root)
    engine = root / 'modules/FlAccessGameplay/engine'
    pieces = ['-- Generated by tools/build_gameplay_module.py; edit engine sources.\n']
    pieces.append('local camera_profiles = {}\n')
    for camera_id in range(10):
        profile = engine / 'cameraRadars' / f'camera_{camera_id:02d}.ini'
        source = profile.read_text(encoding='utf-8')
        delimiter = '='
        while ']' + delimiter + ']' in source:
            delimiter += '='
        pieces.append(f'camera_profiles[{camera_id}] = [{delimiter}[{source}]{delimiter}]\n')
    for name in ('audio', 'registry', 'cameraRadars', 'radar'):
        source = (engine / (name + '.lua')).read_text(encoding='utf-8')
        pieces.append(f'local {name} = (function()\n{source}\nend)()\n')
    pieces.append('''local initialize_radar = radar.init
radar.name = "FlAccessGameplay"
function radar.init(ctx)
    audio.init(ctx)
    registry.init(ctx)
    cameraRadars.init(ctx, camera_profiles)
    initialize_radar(ctx)
end
return radar
''')
    target = root / 'modules/FlAccessGameplay/FlAccessGameplay.lua'
    target.write_text('\n'.join(pieces), encoding='utf-8')
    return target

if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--root', type=Path, default=Path(__file__).resolve().parents[1])
    args = parser.parse_args()
    print('GAMEPLAY_BUNDLE_OK', build(args.root))
